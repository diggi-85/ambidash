// Turns Ambiframe's design export (data/ambiframe-designs.json, made by Ambiframe's frontend/tools/designs.mjs) into
// src/ambiframe.generated.ts: the styles Ambidash does not have by hand, with only the tokens Ambidash uses.
//   node packages/core/tools/import-ambiframe.mjs            (from frontend/; `npm run designs:import`)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const data = JSON.parse(readFileSync(join(here, "../data/ambiframe-designs.json"), "utf8"));

/** Ambiframe's id → the id Ambidash uses (English); styles that Ambidash has by hand keep their hand-made version. */
const NEW = {
  pixel: ["pixel", "Pixel"],
  arcade: ["arcade", "Arcade"],
  cockpit: ["cockpit", "Cockpit"],
  tonal: ["tonal", "Tonal"],
  kacheln: ["tiles", "Tiles"],
  fallblatt: ["flap", "Split-flap"],
  millennium: ["millennium", "Millennium"],
  glanz: ["gloss", "Gloss"],
  handheld: ["handheld", "Handheld"],
  boho: ["boho", "Boho"],
  landhaus: ["cottage", "Cottage"],
  natur: ["nature", "Nature"],
  galerie: ["gallery", "Gallery"],
  zeitung: ["newspaper", "Newspaper"],
  artdeco: ["artdeco", "Art déco"],
  terminal: ["terminal", "Terminal"],
  verspielt: ["playful", "Playful"],
  leitsystem: ["wayfinding", "Wayfinding"],
  lobby: ["lobby", "Lobby"],
  bilderbuch: ["picturebook", "Picture book"],
  weihnachten: ["xmas", "Christmas"],
};

/** What Ambidash uses of Ambiframe's tokens; the rest (photo frames, flaps, panels …) belongs to Ambiframe's own screens. */
const KEEP = new Set([
  "bg", "bg-art", "bg-size", "ink", "ink-2", "ink-3", "line", "surface", "accent", "accent-soft", "cold", "alert", "good",
  "colon", "colon-opacity", "card", "card-tint", "card-border", "card-filter", "card-shadow", "card-rule", "card-radius",
  "display", "sans", "num-font", "clock-weight", "clock-track", "label-case", "label-track", "label-weight", "label-color", "label-font", "fs", "wide",
]);
const pick = (tokens) => Object.fromEntries(Object.entries(tokens).filter(([key]) => KEEP.has(key)));

const themes = data.themes
  .filter((t) => t.id in NEW)
  .map((t) => ({ af: t.id, id: NEW[t.id][0], name: NEW[t.id][1], hint: t.hint, shared: pick(t.shared), dark: pick(t.dark), light: pick(t.light) }));

// Fonts of the styles Ambidash made by hand (and of Ambiframe's seasons style): they take Ambiframe's fonts, not system ones
const FONT_KEYS = ["display", "sans", "label-font", "num-font"];
const fonts = Object.fromEntries(
  data.themes
    .filter((t) => !(t.id in NEW) && !t.id.startsWith("saison-"))
    .map((t) => [t.id, Object.fromEntries(FONT_KEYS.filter((k) => t.shared[k]).map((k) => [k, t.shared[k]]))]),
);
const MARK = "\n//--fonts--\n";
let body = (JSON.stringify(themes, null, 2) + MARK + JSON.stringify(fonts, null, 2)).replace(/"([a-z][\w-]*)":/g, (m, k) => (/^[a-z]\w*$/.test(k) ? `${k}:` : m));
// Long values that repeat (font stacks, page art, shadows) become constants, so the bundle carries each once
const counts = new Map();
for (const [literal] of body.matchAll(/"(?:[^"\\]|\\.)*"/g)) if (literal.length > 40) counts.set(literal, (counts.get(literal) ?? 0) + 1);
const shared = [...counts].filter(([, n]) => n > 1).sort((a, b) => b[1] - a[1]);
const constants = shared.map(([literal], i) => {
  body = body.split(literal).join(`K${i}`);
  return `const K${i} = ${literal};\n`;
});
writeFileSync(
  join(here, "../src/ambiframe.generated.ts"),
  `// Generated by tools/import-ambiframe.mjs from data/ambiframe-designs.json (${data.generated}); do not edit by hand.\n` +
    constants.join("") +
    `\nexport interface AfTheme {\n  af: string;\n  id: string;\n  name: string;\n  hint: string;\n  shared: Record<string, string>;\n  dark: Record<string, string>;\n  light: Record<string, string>;\n}\n\n` +
    `export const AF_THEMES: AfTheme[] = ${body.split(MARK)[0]};\n\n` +
    `/** Fonts of the styles made by hand, by Ambiframe's id */\nexport const AF_FONTS: Record<string, Record<string, string>> = ${body.split(MARK)[1]};\n`,
);
console.log(`${themes.length} styles written`);
